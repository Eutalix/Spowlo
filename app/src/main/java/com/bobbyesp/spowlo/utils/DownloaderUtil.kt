    private fun SpotDLRequest.addAudioProvider(downloadPreferences: DownloadPreferences): SpotDLRequest =
        this.apply {
            if (downloadPreferences.audioProviders.isNotEmpty()) {
                addOption("--audio")
                if (downloadPreferences.audioProviders.contains("YouTube")) addOption("youtube")
                if (downloadPreferences.audioProviders.contains("YouTube Music")) addOption("youtube-music")
                if (downloadPreferences.audioProviders.contains("Soundcloud")) addOption("soundcloud")
                if (downloadPreferences.audioProviders.contains("Bandcamp")) addOption("bandcamp")
                if (downloadPreferences.audioProviders.contains("Piped")) addOption("piped")
            }
        }

    private fun createDownloadRequest(
        url: String,
        downloadPreferences: DownloadPreferences,
    ): SpotDLRequest {
        val request = SpotDLRequest()
        val pathBuilder = StringBuilder()

        with(downloadPreferences) {
            request.apply {
                addOption("download", url)

                pathBuilder.append(audioDownloadDir)
                pathBuilder.buildPathExtensions(downloadPreferences)

                Log.d(TAG, "Download path configured: $pathBuilder")

                addOption("--output", pathBuilder.toString())

                if (useCookies) useCookies()
                if (useYtMetadata) addOption("--ytm-data")
                if (dontFilter) addOption("--dont-filter-results")

                // An empty --lyrics skips spotDL's default lyrics search for every song.
                if (!downloadLyrics || downloadPreferences.lyricProviders.isNotEmpty()) {
                    addOption("--lyrics")
                    if (downloadLyrics) {
                        if (downloadPreferences.lyricProviders.contains("Synced")) addOption("synced")
                        if (downloadPreferences.lyricProviders.contains("Genius")) addOption("genius")
                        if (downloadPreferences.lyricProviders.contains("Musixmatch")) addOption("musixmatch")
                        if (downloadPreferences.lyricProviders.contains("AZLyrics")) addOption("azlyrics")
                    }
                }

                if (sponsorBlock) addOption("--sponsor-block")
                if (onlyVerifiedResults) addOption("--only-verified-results")
                if (skipExplicit) addOption("--skip-explicit")
                if (generateLRC) addOption("--generate-lrc")
                if (skipAlbumArt) addOption("--skip-album-art")

                if (preserveOriginalAudio) {
                    addOption("--bitrate", "disable")
                    addAudioFormat()
                } else {
                    addAudioQuality()
                    addAudioFormat()
                }

                addAudioProvider(downloadPreferences)

                if (useSpotifyPreferences) {
                    if (spotifyClientID.isNotEmpty() && spotifyClientSecret.isNotEmpty()) {
                        addOption("--client-id", spotifyClientID)
                        addOption("--client-secret", spotifyClientSecret)
                    } else {
                        Log.w(TAG, "Custom Spotify credentials enabled but not provided. Falling back to default.")
                    }
                }
            }
        }
        return request
    }

    @CheckResult
    fun downloadSong(
        songInfo: SpotifySong,
        taskId: String,
        downloadPreferences: DownloadPreferences,
        progressCallback: ((Float, Long, String) -> Unit)?
    ): Result<List<String>> {
        if (songInfo.url.isBlank()) return Result.failure(Throwable(context.getString(R.string.fetch_info_error_msg)))

        // SpotipyFree (curl_cffi) does not work on Android, so pass the resolved metadata instead.
        val metadataFile = writeMetadataFile(taskId, listOf(songInfo))

        val request = createDownloadRequest(metadataFile.absolutePath, downloadPreferences)
        val pathBuilder = StringBuilder().append(audioDownloadDir).also { it.buildPathExtensions(downloadPreferences) }
        
        return runCatching {
            SpotDL.getInstance().execute(request, taskId, callback = progressCallback)
        }.also {
            metadataFile.delete()
        }.fold(
            onSuccess = { response ->
                when {
                    response.output.contains("LookupError") -> Result.failure(Throwable("A LookupError occurred. The song wasn't found. Try changing the audio provider."))
                    response.output.contains("YT-DLP") -> Result.failure(Throwable("An error occurred with yt-dlp while downloading. Please report this issue."))
                    response.output.contains("HTTPError") -> Result.failure(Throwable("A HTTPError occurred. Try changing providers."))
                    response.output.contains("ReadTimeout") -> Result.failure(Throwable("A ReadTimeout occurred. Try changing providers."))
                    response.output.contains("ValueError") -> Result.failure(Throwable("A ValueError occurred. Try changing providers."))
                    response.output.contains("Skipping explicit song") -> Result.failure(Throwable("An explicit song has been skipped. Disable 'Skip explicit songs' in settings to download."))
                    else -> onFinishDownloading(
                        preferences = downloadPreferences,
                        songInfo = songInfo,
                        downloadPath = buildPathForDatabase(pathBuilder.toString(), songInfo),
                        consoleOutput = response.output,
                    )
                }
            },
            onFailure = { th ->
                th.printStackTrace()
                if (th.message?.contains("No such file or directory") == true) {
                    onFinishDownloading(
                        preferences = downloadPreferences,
                        songInfo = songInfo,
                        downloadPath = buildPathForDatabase(pathBuilder.toString(), songInfo),
                        consoleOutput = th.message.orEmpty(),
                    )
                } else {
                    Result.failure(th)
                }
            }
        )
    }

    /** Writes the `spotdl --save-file` format that `spotdl download <file>` reads. */
    private fun writeMetadataFile(taskId: String, songs: List<SpotifySong>): File {
        val directory = File(context.cacheDir, "spotdl_meta").apply { mkdirs() }
        val name = taskId.replace(Regex("[^A-Za-z0-9._-]"), "_").take(64).ifBlank { "song" }
        val file = File(directory, "$name.spotdl")
        file.writeText(json.encodeToString(songs))
        return file
    }

    @CheckResult
    private fun onFinishDownloading(
        preferences: DownloadPreferences,
        songInfo: SpotifySong,
        downloadPath: String,
        consoleOutput: String = "",
    ): Result<List<String>> = preferences.run {
        if (incognitoMode) {
            Result.success(emptyList())
        } else if (sdcard) {
            Result.success(moveFilesToSdcard(
                sdcardUri = sdcardUri, tempPath = context.getSdcardTempDir(songInfo.song_id)
            ).apply {
                insertInfoIntoDownloadHistory(songInfo, this, consoleOutput)
            })
        } else {
            Result.success(
                scanSongIntoDownloadHistory(
                    songInfo = songInfo,
                    downloadPath = downloadPath,
                    consoleOutput = consoleOutput,
                )
            )
        }
    }

    @CheckResult
    private fun scanSongIntoDownloadHistory(
        songInfo: SpotifySong,
        downloadPath: String,
        consoleOutput: String = "",
    ): List<String> {
        // Fall back to the downloads root if the output template has unresolved placeholders.
        val scanRoot = downloadPath.takeIf { File(it).exists() } ?: audioDownloadDir
        return FilesUtil.scanFileToMediaLibraryPostDownload(
            title = songInfo.name, downloadDir = scanRoot
        ).apply {
            Log.d(TAG, "scanSongIntoDownloadHistory: $scanRoot")
            insertInfoIntoDownloadHistory(songInfo, this, consoleOutput)
        }
    }

    private fun insertInfoIntoDownloadHistory(
        songInfo: SpotifySong,
        filePaths: List<String>,
        consoleOutput: String = "",
    ) {
        filePaths.forEach { filePath ->
            DatabaseUtil.insertInfo(
                DownloadedSongInfo(
                    songName = songInfo.name,
                    songAuthor = songInfo.artist,
                    songUrl = songInfo.url,
                    thumbnailUrl = songInfo.cover_url,
                    songPath = filePath,
                    songDuration = songInfo.duration ?: 0.0,
                    extractor = "Youtube Music",
                    consoleOutput = consoleOutput.takeLast(MAX_STORED_LOG_LENGTH),
                    downloadedAt = System.currentTimeMillis(),
                )
            )
        }
    }

    private const val MAX_STORED_LOG_LENGTH = 100_000

    suspend fun executeParallelDownload(songInfo: SpotifySong, name: String) {
        val url = songInfo.url
        val taskId = Downloader.makeKey(url, url.reversed())
        ToastUtil.makeToastSuspend(context.getString(R.string.download_started_msg))

        val downloadPreferences = DownloadPreferences()
        val metadataFile = writeMetadataFile(taskId, listOf(songInfo))
        val pathBuilder = StringBuilder().append(audioDownloadDir).also {
            it.buildPathExtensions(downloadPreferences)
        }
        val request = createDownloadRequest(metadataFile.absolutePath, downloadPreferences).apply {
            addOption("--threads", downloadPreferences.threads.toString())
        }

        Downloader.onProcessStarted()
        Downloader.onTaskStarted(
            url = url,
            name = songInfo.name.ifBlank { name },
            artist = songInfo.artist,
            artworkUrl = songInfo.cover_url,
        )
        
        runCatching {
            val response = SpotDL.getInstance().execute(
                request = request,
                processId = taskId,
                callback = { progress, _, text ->
                    NotificationsUtil.makeNotificationForParallelDownloads(
                        notificationId = taskId.hashCode(),
                        taskId = taskId,
                        progress = progress.roundToInt(),
                        text = text,
                        extraString = "$name - ${context.getString(R.string.parallel_download)}",
                        taskUrl = url,
                    )
                    Downloader.updateTaskOutput(
                        url = url, line = text, progress = progress, isPlaylist = false
                    )
                })
            val finalResponse = removeDuplicateLines(clearLinesWithEllipsis(response.output))
            onFinishDownloading(
                preferences = downloadPreferences,
                songInfo = songInfo,
                downloadPath = buildPathForDatabase(pathBuilder.toString(), songInfo),
                consoleOutput = finalResponse,
            )
            Downloader.onTaskEnded(url, finalResponse, name)
        }.onFailure {
            Log.e(TAG, "Parallel download failed", it)
            ToastUtil.makeToastSuspend(context.getString(R.string.download_error_msg))
            if (it is CanceledException) return@onFailure
            it.message.run {
                if (isNullOrEmpty()) Downloader.onTaskEnded(url)
                else Downloader.onTaskError(this, url)
            }
        }
        Downloader.onProcessEnded()
        metadataFile.delete()
        ToastUtil.makeToastSuspend(context.getString(R.string.download_finished_msg))
    }

    suspend fun executeCollectionDownload(collection: SpotifyCollection, fallbackName: String) {
        if (collection.songs.isEmpty()) {
            ToastUtil.makeToastSuspend(context.getString(R.string.collection_empty))
            return
        }

        val url = collection.url
        val taskId = Downloader.makeKey(url, url.reversed())
        val taskName = collection.name.ifBlank { fallbackName }
        ToastUtil.makeToastSuspend(context.getString(R.string.download_started_msg))

        val downloadPreferences = DownloadPreferences()
        val metadataFile = writeMetadataFile(taskId, collection.songs)
        val request = createDownloadRequest(metadataFile.absolutePath, downloadPreferences).apply {
            addOption("--threads", downloadPreferences.threads.toString())
        }
        val startedAt = System.currentTimeMillis()

        Downloader.onProcessStarted()
        Downloader.onTaskStarted(
            url = url,
            name = taskName,
            artist = collection.artist,
            artworkUrl = collection.artworkUrl,
        )

        runCatching {
            val response = SpotDL.getInstance().execute(
                request = request,
                processId = taskId,
                callback = { progress, _, text ->
                    NotificationsUtil.makeNotificationForParallelDownloads(
                        notificationId = taskId.hashCode(),
                        taskId = taskId,
                        progress = progress.roundToInt(),
                        text = text,
                        extraString = "$taskName - ${context.getString(R.string.parallel_download)}",
                        taskUrl = url,
                    )
                    Downloader.updateTaskOutput(
                        url = url, line = text, progress = progress, isPlaylist = true
                    )
                })
            val finalResponse = removeDuplicateLines(clearLinesWithEllipsis(response.output))
            if (!downloadPreferences.incognitoMode) {
                insertCollectionIntoDownloadHistory(collection.songs, finalResponse, startedAt)
            }
            Downloader.onTaskEnded(url, finalResponse, taskName)
        }.onFailure {
            Log.e(TAG, "Collection download failed", it)
            ToastUtil.makeToastSuspend(context.getString(R.string.download_error_msg))
            if (it is CanceledException) return@onFailure
            it.message.run {
                if (isNullOrEmpty()) Downloader.onTaskEnded(url)
                else Downloader.onTaskError(this, url)
            }
        }
        Downloader.onProcessEnded()
        metadataFile.delete()
        ToastUtil.makeToastSuspend(context.getString(R.string.download_finished_msg))
    }

    private fun insertCollectionIntoDownloadHistory(
        songs: List<SpotifySong>,
        consoleOutput: String,
        startedAt: Long,
    ) {
        val files = File(audioDownloadDir)
            .walkTopDown()
            .filter { it.isFile && it.extension.lowercase() in AUDIO_EXTENSIONS }
            .filter { it.lastModified() >= startedAt - NEW_FILE_TOLERANCE_MS }
            .toList()
        if (files.isEmpty()) return

        val usedPaths = mutableSetOf<String>()
        val log = consoleOutput.takeLast(MAX_COLLECTION_LOG_LENGTH)

        songs.forEach { song ->
            val candidates = files.filter {
                it.absolutePath !in usedPaths && it.matchesTitle(song.name)
            }
            val match = candidates.firstOrNull { it.matchesArtist(song) } ?: candidates.firstOrNull()
                ?: return@forEach
            usedPaths += match.absolutePath
            insertInfoIntoDownloadHistory(song, listOf(match.absolutePath), log)
        }
    }

    private fun File.matchesTitle(title: String): Boolean {
        val titleKey = title.matchKey()
        return titleKey.isNotEmpty() && nameWithoutExtension.matchKey().contains(titleKey)
    }

    private fun File.matchesArtist(song: SpotifySong): Boolean {
        val fileKey = nameWithoutExtension.matchKey()
        return (song.artists + song.artist).any { artist ->
            val artistKey = artist.matchKey()
            artistKey.isNotEmpty() && fileKey.contains(artistKey)
        }
    }

    private fun String.matchKey(): String = lowercase().filter { it.isLetterOrDigit() }

    private val AUDIO_EXTENSIONS = setOf("mp3", "flac", "ogg", "opus", "m4a", "wav")
    private const val MAX_COLLECTION_LOG_LENGTH = 8_000
    private const val NEW_FILE_TOLERANCE_MS = 5_000L

    fun clearLinesWithEllipsis(input: String): String {
        return input.split("\n").filterNot { it.contains("…") }.joinToString("\n")
    }

    fun removeDuplicateLines(input: String): String {
        return input.split("\n").distinct().joinToString("\n")
    }

    fun buildPathForDatabase(path: String, songInfo: SpotifySong = SpotifySong()): String {
        var newPath = path

        newPath = newPath.replace("\\{album\\}".toRegex(), songInfo.album_name)
        newPath = newPath.replace("\\{artist\\}".toRegex(), songInfo.artist)
        newPath = newPath.replace("\\{artists\\}".toRegex(), songInfo.artists.joinToString(", ").ifBlank { songInfo.artist })
        newPath = newPath.replace("\\{title\\}".toRegex(), songInfo.name)
        newPath = newPath.replace("\\{album-artist\\}".toRegex(), songInfo.album_artist)
        newPath = newPath.replace("\\{genre\\}".toRegex(), songInfo.genres?.joinToString() ?: "")
        newPath = newPath.replace("\\{year\\}".toRegex(), songInfo.year?.toString() ?: "0")
        newPath = newPath.replace("\\{output-ext\\}".toRegex(), getExtension() ?: "")

        return newPath
    }

    fun getExtension(): String? {
        val audioFormat = PreferencesUtil.getAudioFormat()
        return when (audioFormat) {
            0 -> "mp3"
            1 -> "flac"
            2 -> "ogg"
            3 -> "opus"
            4 -> "m4a"
            5 -> "wav"
            else -> null
        }
    }
