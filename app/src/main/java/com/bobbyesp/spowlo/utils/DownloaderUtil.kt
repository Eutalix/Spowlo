    private fun SpotDLRequest.useCookies(): SpotDLRequest = this.apply {
        if (!PreferencesUtil.getValue(COOKIES)) return@apply
        addOption("--cookie-file", context.ytDlpCookiesFile().absolutePath)
    }

    private fun SpotDLRequest.useJsRuntime(): SpotDLRequest = this.apply {
        context.quickJsRuntime()?.let { qjs ->
            addOption(
                "--yt-dlp-args",
                "--js-runtimes quickjs:${qjs.absolutePath} --remote-components ejs:github"
            )
        }
    }

    /** yt-dlp rewrites the cookie file it reads, so use a copy. */
    private fun Context.ytDlpCookiesFile(): File {
        val source = getCookiesFile()
        if (!source.exists()) return source

        val copy = File(source.parentFile, "cookies_ytdlp.txt")
        return runCatching {
            source.copyTo(copy, overwrite = true)
            copy
        }.getOrDefault(source)
    }

    private fun Context.quickJsRuntime(): File? {
        val version = runCatching {
            SpotDLDependencyUpdater.getLocalYtDlpVersion(this)
        }.getOrDefault("")
        if (!version.supportsJsRuntime()) return null

        return File(applicationInfo.nativeLibraryDir, "libqjs_bin.so").takeIf { it.canExecute() }
    }

    private fun String.supportsJsRuntime(): Boolean {
        val parts = split('.').mapNotNull { it.toIntOrNull() }
        if (parts.size < 3) return false
        for (i in 0..2) {
            if (parts[i] != MIN_YT_DLP_JS_VERSION[i]) return parts[i] > MIN_YT_DLP_JS_VERSION[i]
        }
        return true
    }

